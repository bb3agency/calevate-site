export interface TestHistoryEntry {
  id: string;
  created_at: string;
  prompt_version: number | null;
  round: number;
  score: TestScore;
}

export interface TestConversations {
  available: boolean;
  unavailable_reason: string | null;
  cost_note: string;
  /** Why the agent under test is behind the instructions every agent gets. */
  waiting_update?: string | null;
  latest: TestRun | null;
  history: TestHistoryEntry[];
}

const testsKey = (org: string, agentId: string) => ["script-tests", org, agentId] as const;

/** The agent's latest test run and score history. Polls while a run is queued or running. */
export function useTestConversations(
  session: Session,
  agentId: string,
): UseQueryResult<TestConversations, Error> {
  return useQuery({
    queryKey: testsKey(session.orgSlug, agentId),
    queryFn: () => apiRequest<TestConversations>(session, `${base(agentId)}/tests`),
    refetchInterval: (query) => {
      const latest = query.state.data?.latest;
      const busy = latest?.status === "queued" || latest?.status === "running" || latest?.improving === true;
      return busy ? 3000 : false;
    },
  });
}

/** Start a run (or get the one already running). `retest_of` is "Test again" after a fix. */
export function useRunTestConversations(
  session: Session,
  agentId: string,
): UseMutationResult<TestConversations, Error, { retest_of?: string | null; auto_improve?: boolean } | void> {
  const client = useQueryClient();
  return useMutation({
    mutationFn: (body) =>
      apiRequest<TestConversations>(session, `${base(agentId)}/tests`, { method: "POST", body: body ?? {} }),
    onSuccess: (data) => client.setQueryData(testsKey(session.orgSlug, agentId), data),
  });
}

/**
 * "Improve my agent" (all failures) or "Fix this" (`keys`). Queued on the server (202); the
 * run reads `improving` until the proposal arrives, and the tests query polls meanwhile.
 */
export function useImproveFromTests(
  session: Session,
  agentId: string,
): UseMutationResult<TestConversations, Error, { runId: string; keys?: string[] }> {
  const client = useQueryClient();
  return useMutation({
    mutationFn: ({ runId, keys }) =>
      apiRequest<TestConversations>(session, `${base(agentId)}/tests/${runId}/improve`, {
        method: "POST",
        body: keys ? { keys } : {},
      }),
    onSuccess: (data) => client.setQueryData(testsKey(session.orgSlug, agentId), data),
  });
}
