"use client";

/**
 * Client-realm structured call-script builder hooks — `/v1/agents/{id}/script/...`.
 *
 * This is the exception's exception. `agents.ts` is read-only but for `useSetDisclosure`,
 * on D-21's ground that a script change routes through us. The founder's APPROVED DECISION
 * makes the STRUCTURED builder the primary client authoring surface, so these mutation
 * hooks exist — reconciled with D-21 rather than overriding it: every save STAGES (the
 * server's slow lane), and nothing reaches a live call until an explicit `useApplyScript`.
 * See `apps/api/agents/script_routes.py` for the flagged conflict and its resolution.
 *
 * ⚠ TYPES ARE HAND-DECLARED, NOT ALIASED FROM `./schema`, and this is a KNOWN DEVIATION
 * from the generated-client doctrine. The OpenAPI snapshot and the TS schema are
 * regenerated by `pnpm gen:api` against a RUNNING API; these endpoints are new, so until
 * that is run they are absent from `components["schemas"]`. The shapes below mirror the
 * Pydantic models in `script_routes.py` exactly; fold them into the generated aliases the
 * next time `gen:api` runs (the same staleness `agents/routes.py` already flags for the
 * publish path). Keeping them typed here rather than `any` means the builder still gets
 * real checking in the meantime.
 */

