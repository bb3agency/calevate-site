"""The retention policies every new tenant is given (SEC-COMP §1).

`retention_policies` is tenant-scoped, so these are not global rows: account creation
(`admin/service.create_organization`) writes them for each new organization, and the
engine's retention reads the same defaults (`workers/engine_retention`).
"""

from __future__ import annotations

from typing import Any, Final

# Retention: SEC-COMP §1. The DB enforces a 90-day floor on `recording`
# (CheckConstraint recording_ttl_floor) — do not lower it here, it will fail.
DEFAULT_RETENTION_POLICIES: Final[tuple[dict[str, Any], ...]] = (
    # OUR copies of call recordings are kept 90 days (founder, 3 Oct 2026, D-668), which is
    # also the TRAI floor the DB CHECK and `workers/retention.RECORDING_FLOOR_DAYS` hold, so
    # the default can be neither lower nor, without a decision, higher. The `recordings/`
    # bucket rule sits at 120 days behind it (`infra/object-lifecycle/policy.json`).
    {"data_category": "recording", "ttl_days": 90, "action": "delete"},
    # This clock also carries `scheduled_callbacks` — a promised call-back's number and
    # the model's note of what the caller wanted — because that note is one sentence about
    # one conversation and belongs with the words it paraphrases, exactly like the
    # handover brief and the summary (`workers/retention.DERIVED_COPIES`).
    {"data_category": "transcript", "ttl_days": 365, "action": "anonymize"},
    # 1095 days covers MORE THAN `leads` AND `call_extractions`, and the extra is the
    # point rather than a footnote: `campaign_contacts` — the contact list a client pastes
    # into a campaign, holding a name, a number and every other column of their CSV for
    # people who may never have been dialled — rides this same clock
    # (`workers/retention.DERIVED_COPIES`). It had no clock at all until then, which made
    # it the one store of a data principal's details that only a §12 request could ever
    # empty. It rides an agreed, published period rather than getting a category of its
    # own because the number a new category needs is a DPA term the founder gives; this
    # one is already given, already published (`/legal/privacy` §9) and already ENDS.
    {"data_category": "lead", "ttl_days": 1095, "action": "anonymize"},
    # consent_log is an append-only ledger (hard rule 4) — retained, never purged
    # on a timer; kept here so the category is explicit rather than forgotten.
    {"data_category": "consent_log", "ttl_days": 2555, "action": "anonymize"},
    # The archived RAW vendor document per call (D-126), which carries the caller's
    # number and the transcript. 90 days is not a new number: it is the period
    # `infra/object-lifecycle/policy.json` already assigns the `engine-payloads/`
    # prefix — what D-179 changes is that a mechanism which actually runs enforces it,
    # rather than a bucket rule nothing has ever applied (infra/README §5).
    {"data_category": "engine_payload", "ttl_days": 90, "action": "delete"},
    # SUPERSEDED knowledge-base versions (D-179). The live version is never expired by
    # this — see `apps/workers/retention._KB_EXPIRE_SQL` — so the clock runs only on
    # content no screen shows. 365 days matches the transcript default rather than
    # inventing a third number: it is content of the same class, and rolling back a bad
    # publish (FLOWS §7) is a thing clients do in days.
    {"data_category": "kb", "ttl_days": 365, "action": "delete"},
    # What the in-app copilot remembers (migration d4a9c17e6b02, which seeds the same pair
    # for every organisation that already existed — so old and new tenants agree). 180
    # days: shorter than the transcript clock because nothing depends on these rows — they
    # are working context, regenerated by use, and the client bought none of it — and
    # `delete` because there is no anonymised form of a sentence (the `kb` arm's argument).
    {"data_category": "copilot_memory", "ttl_days": 180, "action": "delete"},
    # What an AGENT remembers about a CALLER between calls (D-507).
    # 180/`delete` is `copilot_memory`'s pair rather than a fifth number, and the arguments
    # transfer intact: nothing depends on these rows, use regenerates them, and there is no
    # anonymised form of a sentence. It is NOT the transcript's 365 — that is the clock for
    # what someone said on one call, and a memory whose whole purpose is to outlive the
    # call must not inherit the call's period by default. It is a PLATFORM ceiling in
    # practice: a client raising this slider raises how long their agent remembers a person
    # who never chose us, which the spoken notice (D-507) does not restate.
    {"data_category": "caller_memory", "ttl_days": 180, "action": "delete"},
)
