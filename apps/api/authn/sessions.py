"""Opaque server-side sessions: issue, verify, rotate, revoke (D-165).

═══ WHAT A SESSION IS HERE ═══

A 256-bit random string the browser holds in an `HttpOnly` cookie, and a row that IS the
session. The string carries no claims, so there is nothing in it to trust and nothing to
verify cryptographically; every question about it — is it live, whose is it, which realm,
did it pass MFA, when does it die — is answered by the row. That is the property this
product cannot trade away: **revocation takes effect on the next request**, with no
denylist, no token lifetime to tune down, and no window during which a removed staff
member, a deactivated operator or a halted tenant still has a valid credential in hand.

Rejected: a stateless JWT session. It is the fashionable answer and it is the wrong one
for a dashboard whose authorization is re-read per request anyway (`core/auth.py`
re-checks `is_active` and `admin_users` on every call, BACKEND-PATTERNS §7), because the
only way to revoke one is a server-side denylist — which is a session table with worse
ergonomics and a failure mode where the denylist being down means revocation silently
stops working. OWASP's ASVS 5.0 moved self-contained tokens into their own chapter (V9)
precisely because their operational requirements — key rotation, revocation — are the
part people skip. We already run one signed-token design (`core/impersonation.py`'s
15-minute view-as grant) and it is signed exactly because it is NOT a credential and
needs no revocation of its own.

═══ THE REALM BOUNDARY, WHICH IS THE DANGEROUS PART ═══

The two realms used to be two Clerk applications with two JWKS endpoints, so an admin
token was not a weak client token — it was not a token at all. Both realms are ours since
D-177, so that separation is rebuilt out of our own materials, and "a `realm` column we
remember to filter on" is not good enough: it is one forgotten WHERE clause away from
being nothing, and the forgotten clause would be silent.

So the realm is INSIDE THE HASH. `token_fingerprint` domain-separates on it, which means
the stored fingerprint of a client token computed under the admin realm is a different
32 bytes — there is no value the admin lookup could compare it against and match. Passing
a client's token to `verify_session(..., realm="admin")` therefore returns "no such
session" as a matter of arithmetic, before any column is read. The `AND realm = :realm`
predicate in the query stays anyway, as the belt to that brace: two independent reasons
for the same refusal, and `tests/authn_session_test.py` drives both.

═══ ROTATION AND REUSE DETECTION ═══

OWASP's Session Management Cheat Sheet requires the session identifier to be "renewed or
regenerated by the web application after any privilege level change", which is the
session-fixation defence. `rotate_session` is that: it mints a new token, marks the old
row `superseded_at` under a compare-and-swap, and inserts a new row carrying the same
`family_id` and the same `absolute_expires_at` — rotation refreshes the CREDENTIAL, never
the lifetime, or a session that rotates often would live forever.

Because the old row survives with `superseded_at` set, presenting the old token later is
DETECTABLE, and it is treated as theft rather than as a stale tab: the whole family is
revoked with `reuse_detected`. That is RFC 9700 §4.14.2's refresh-token reuse rule, and
the reference implementation this migration learns from arrived at the same answer the
expensive way — its pentest finding F-2 (2026-08-15) was exactly a replayed rotated
token being read as a stale request.

**WITHOUT ITS CONCURRENCY GRACE WINDOW**, which is the one design decision here that
departs from that reference, so it is argued rather than assumed. Their rotation happens
on every access-token refresh, so parallel tabs racing the same refresh token is the
ORDINARY case and a 10-second grace was the only way to stop legitimate users being
logged out. Ours does not rotate on a schedule, so a burst of background fetches racing
one token is not a state this design has to survive — and the grace window it would cost
is a 10-second replay window on a stolen cookie.

**WHICH ACTS ROTATE IS THEREFORE LOAD-BEARING, AND THIS PARAGRAPH USED TO NAME THE WRONG
THREE.** It said "PRIVILEGE CHANGE ONLY — sign-in, MFA completion, role change", and two
of those are not rotations at all: `service.sign_in` ISSUES a new family (a sign-in has no
prior session of ours to rotate, which is what makes it a fixation defence), and a role
change REVOKES (`operators.set_operator_role` → `revoke_subject_sessions`; the role itself
is re-read from `admin_users` on every request, so nothing is left to re-mint). The census
in `tests/authn_session_test.py::test_the_only_rotation_callers_are_the_four_recorded_here`
reads the tree rather than this sentence, so the list below cannot go stale again:

  1. `service.complete_second_factor` — a second factor proved. A privilege change.
  2. `service.complete_step_up` — a factor re-proved for a dangerous act. A privilege change.
  3. `service.change_password`, behind `POST /v1/auth/{realm}/password/change` — the
     current password was re-proved, which ASVS 5.0 7.2.4 treats as authentication; and
     the caller's surviving session must not be the one a thief copied the cookie of.
  4. `service.refresh`, behind `POST /v1/auth/{realm}/session/refresh` — **NOT a privilege
     change.** It is the console's idle-extension button (`apps/web/src/components/authn/
     adminIdleTimeoutModal.tsx`), so it is the one caller a client can reach at will and
     the one this decision actually rests on.

**WHERE THE "NEVER A BURST" PREMISE IS ENFORCED, since it is not enforced here.** It is a
requirement on the browser, and `apps/web/src/lib/authn/realm.ts` states it as one and
carries the two mechanisms that hold it up: a single-flight plus result cache so concurrent
callers in one tab collapse into one rotation, and a rotation BARRIER that makes every
other call to that realm wait, so no request is carrying the old cookie at the moment the
new one is minted. `tests/authnSession.test.ts` drives both.

**WHAT IS LEFT, STATED RATHER THAN IMPLIED.** Those mechanisms are per JavaScript context,
and two tabs share one cookie jar — so two `POST /session/refresh` calls overlapping across
tabs would have the second present a superseded token and revoke the family. The outcome is
a forced sign-out, not an entry: it fails in the direction this module prefers, it needs two
tabs to reach the idle warning and be clicked inside the same round trip, and closing it
would mean buying back the replay window above. If a SERVER-side rotation caller is ever
added — a periodic re-mint, a middleware, anything that fires without a person clicking —
that trade changes and this paragraph is what it invalidates, which is why the census test
exists.

═══ TIMEOUTS ═══

Both bounds are enforced server-side, on the row, per OWASP: an idle bound so an
unattended browser stops being a credential, and an absolute bound so a stolen cookie
stops being one even while the victim keeps working. The two realms get different numbers
because their blast radii differ by an order of magnitude — see `REALM_TIMEOUTS`.

An operator may switch "Stay signed in" on for their own account (D-766), and then their
second-factor-complete sessions take the client realm's numbers. The switch is read on
every verification, not copied into the row at issue, so switching it off shortens every
live session on that operator's next request — see `session_policy` and `_verify_within`.

═══ WHO OWNS THE TRANSACTION ═══

Everything here takes an `AsyncSession` — a sign-in is a credential check, a session
insert and an audit row, and those belong in one transaction — with ONE exception.
`verify_session` opens its own, because the family revocation it performs on a replayed
token has to survive the refusal that same branch produces; its docstring argues it, and
`tests/authn_session_test.py::test_replaying_a_rotated_token_revokes_the_whole_family`
is the test that goes red if it is ever taken back.
"""

