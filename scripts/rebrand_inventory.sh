#!/usr/bin/env bash
# Every occurrence of the product name in the tracked tree, one row per occurrence, so the
# rename (docs/REBRAND-MAP.md) can be checked off line by line and re-run on the day.
#
#   scripts/rebrand_inventory.sh [OUT_DIR]     # default docs/rebrand
#
# Writes OUT_DIR/inventory.tsv (path, line, token, kind, area, in_comment) and
# OUT_DIR/INVENTORY.md (counts by kind and area, then every file with its counts).
# `in_comment` is a heuristic on the line's first characters (#, //, *, /*, <!--, ;); a
# docstring line reads as code. Binary files are listed separately: a logo carries the name
# in its pixels, which no text search finds.
set -euo pipefail
export MSYS_NO_PATHCONV=1

root=$(git rev-parse --show-toplevel)
cd "$root"
out=${1:-docs/rebrand}
mkdir -p "$out"
tsv="$out/inventory.tsv"
md="$out/INVENTORY.md"

# The inventory files themselves are excluded, or every run would count the last one.
git grep -I -n -i -E 'calevate' -- . ":!$out/inventory.tsv" ":!$out/INVENTORY.md" \
  | awk '
    BEGIN { FS = ":"; OFS = "\t"; print "path", "line", "token", "kind", "area", "in_comment" }
    {
      path = $1; line = $2
      text = substr($0, length(path) + length(line) + 3)
      trimmed = text; sub(/^[ \t]+/, "", trimmed)
      comment = (trimmed ~ /^(#|\/\/|\*|\/\*|<!--|;)/) ? "yes" : "no"
      n = split(path, seg, "/")
      area = seg[1]
      if (area == "apps" || area == "packages" || area == "infra" || area == ".github") area = seg[1] "/" seg[2]
      if (n == 1) area = "(root)"
      rest = text
      while (match(tolower(rest), /[a-z0-9_.@-]*calevate[a-z0-9_.:@\/-]*/)) {
        token = substr(rest, RSTART, RLENGTH)
        low = tolower(token)
        if (low ~ /calevate[_-]shared/) kind = "package"
        else if (low ~ /@calevate\./) kind = "email"
        else if (low ~ /calevate\.tech/) kind = "domain"
        else if (token ~ /^__host-|^__Host-/) kind = "cookie"
        else if (token ~ /CALEVATE_[A-Z]/) kind = "env-var"
        else if (token ~ /Calevate|CALEVATE/) kind = "brand-text"
        else if (low ~ /^\/|calevate\//) kind = "path"
        else if (low ~ /calevate-[a-z@]+\.(service|timer)|calevate-[a-z-]+$/) kind = "identifier-dash"
        else if (low ~ /calevate[_:.]/) kind = "identifier"
        else kind = "identifier"
        print path, line, token, kind, area, comment
        rest = substr(rest, RSTART + RLENGTH)
      }
    }' > "$tsv"

total=$(($(wc -l < "$tsv") - 1))
files=$(tail -n +2 "$tsv" | cut -f1 | sort -u | wc -l)

{
  echo "# Rename inventory"
  echo
  echo "Generated by \`scripts/rebrand_inventory.sh\` at commit \`$(git rev-parse --short HEAD)\`."
  echo "Re-run it on the day of the rename: the counts below go stale with every commit."
  echo "Every occurrence, with line numbers, is in \`inventory.tsv\` beside this file."
  echo
  echo "**$total occurrences in $files files.**"
  echo
  echo "## By kind"
  echo
  echo "| Kind | Occurrences | In code (not comment) | Files |"
  echo "|---|---:|---:|---:|"
  tail -n +2 "$tsv" | awk -F'\t' '{c[$4]++; if ($6=="no") k[$4]++; f[$4 SUBSEP $1]=1}
    END {for (x in f) {split(x, p, SUBSEP); n[p[1]]++}
         for (x in c) printf "| %s | %d | %d | %d |\n", x, c[x], k[x], n[x]}' | sort -t'|' -k3 -nr
  echo
  echo "Kinds: \`brand-text\` = the name as written to people (Calevate, CALEVATE);"
  echo "\`domain\`/\`email\` = calevate.tech; \`package\` = the Python package calevate_shared /"
  echo "calevate-shared; \`env-var\` = CALEVATE_* settings; \`cookie\` = __Host-calevate_*;"
  echo "\`path\` = file-system paths; \`identifier\`/\`identifier-dash\` = every other internal"
  echo "name (units, keys, prefixes, project and service names)."
  echo
  echo "## By area"
  echo
  echo "| Area | Occurrences | Files |"
  echo "|---|---:|---:|"
  tail -n +2 "$tsv" | awk -F'\t' '{c[$5]++; f[$5 SUBSEP $1]=1}
    END {for (x in f) {split(x, p, SUBSEP); n[p[1]]++}
         for (x in c) printf "| %s | %d | %d |\n", x, c[x], n[x]}' | sort -t'|' -k3 -nr
  echo
  echo "## Distinct internal names"
  echo
  echo "Every distinct \`identifier\`, \`identifier-dash\`, \`env-var\`, \`cookie\` and \`path\` token,"
  echo "with how often it occurs. Each needs a decided replacement before the rename."
  echo
  echo "| Token | Kind | Occurrences |"
  echo "|---|---|---:|"
  tail -n +2 "$tsv" | awk -F'\t' '$4 ~ /identifier|env-var|cookie|path/ {
      t=$3; gsub(/[.:,;]+$/, "", t); c[t "\t" $4]++}
    END {for (x in c) {split(x, p, "\t"); printf "| `%s` | %s | %d |\n", p[1], p[2], c[x]}}' \
    | sort -t'|' -k4 -nr
  echo
  echo "## Files whose NAME carries the brand"
  echo
  git ls-files | grep -i calevate | sed 's/^/- `/; s/$/`/'
  echo
  echo "## Images and other binary files to re-make or check by eye"
  echo
  echo "Text search cannot see a name drawn in pixels. Every tracked image, PDF and font:"
  echo
  git ls-files | grep -i -E '\.(png|jpe?g|gif|webp|svg|ico|pdf|woff2?|ttf|otf)$' \
    | grep -v -E '^(thinnest-findings|bolna-findings)/' | sed 's/^/- `/; s/$/`/'
  echo
  echo "## Every file"
  echo
  echo "| File | Occurrences | In code | Kinds |"
  echo "|---|---:|---:|---|"
  tail -n +2 "$tsv" | awk -F'\t' '{c[$1]++; if ($6=="no") k[$1]++; ks[$1 SUBSEP $4]=1}
    END {for (x in ks) {split(x, p, SUBSEP); kinds[p[1]] = kinds[p[1]] (kinds[p[1]] ? ", " : "") p[2]}
         for (x in c) printf "| `%s` | %d | %d | %s |\n", x, c[x], k[x], kinds[x]}' | sort
} > "$md"

echo "$total occurrences in $files files -> $tsv, $md"
